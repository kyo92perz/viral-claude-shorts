#!/usr/bin/env python3
"""WHAT IF? episodes: world.ts = videos/wi-kit.ts + the episode's world-ep.ts. Run from the repo root:
python3 videos/wi-build-world.py videos/wi-<ep>"""
import os, sys
V = sys.argv[1]; K = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'wi-kit.ts')
open(os.path.join(V, 'world.ts'), 'w').write('// GENERATED by videos/wi-build-world.py: edit wi-kit.ts or world-ep.ts, not this file\n' + open(K).read() + '\n' + open(os.path.join(V, 'world-ep.ts')).read())
